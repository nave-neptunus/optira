"""Generate docs/figures/synthetic_signal.png from a synthetic signal.

The signal is made up: a smooth dip plus Gaussian noise (seed 0, 30 fps, 6 s).
It is not real data and says nothing about pupils. The point is to show what
each of the three features measures in this code.
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from optira.features import compute_features
from optira.filtering import safe_lowpass

SEED = 0
FPS = 30
DURATION_S = 6.0
BASELINE_PX = 30.0
DEPTH_PX = 6.0
DIP_CENTER_S = 2.0
DIP_WIDTH_S = 0.6
NOISE_SD_PX = 0.35

OUT = Path(__file__).resolve().parents[1] / "docs" / "figures" / "synthetic_signal.png"


def make_signal():
    rng = np.random.default_rng(SEED)
    t = np.arange(int(DURATION_S * FPS)) / FPS
    dip = DEPTH_PX * np.exp(-(((t - DIP_CENTER_S) / DIP_WIDTH_S) ** 2))
    return t, BASELINE_PX - dip + rng.normal(0.0, NOISE_SD_PX, t.size)


def main():
    t, raw = make_signal()
    filt = safe_lowpass(raw, FPS)
    feats = compute_features(t, raw, FPS)

    baseline = float(np.mean(filt[: int(0.5 * FPS)]))
    min_idx = int(np.argmin(filt))
    t_min, v_min = float(t[min_idx]), float(filt[min_idx])
    win_lo, win_hi = t_min + 0.5, t_min + 2.5

    fig, ax = plt.subplots(figsize=(16, 8), dpi=100)
    ax.plot(t, raw, color="0.65", lw=1.2, label="raw")
    ax.plot(t, filt, color="tab:blue", lw=2.6, label="filtered (4 Hz low-pass)")
    ax.plot([t_min], [v_min], "o", color="tab:red", ms=10, zorder=5, label="minimum")

    # Feature 1: time to minimum, from video start.
    ax.axvline(t_min, color="tab:red", ls=":", lw=1.5)
    ax.annotate(
        "", xy=(0, 32.0), xytext=(t_min, 32.0),
        arrowprops=dict(arrowstyle="<->", color="tab:red", lw=1.5),
    )
    ax.text(
        t_min / 2, 32.3, f"1. time to minimum = {feats['plr_latency']:.2f} s\n(from video start)",
        ha="center", va="bottom", color="tab:red", fontsize=13,
    )

    # Feature 2: mean rate of decline, baseline to minimum.
    ax.plot([0, t_min], [baseline, v_min], color="tab:green", ls="--", lw=2)
    ax.text(
        0.1, 25.4,
        f"2. mean rate of decline\n= {feats['constriction_velocity']:.2f} px/s\n(baseline to minimum)",
        ha="left", va="top", color="tab:green", fontsize=13,
    )

    # Feature 3: post-minimum variability window.
    ax.axvspan(win_lo, win_hi, color="tab:orange", alpha=0.18)
    ax.text(
        (win_lo + win_hi) / 2, 33.4,
        f"3. post-minimum variability = {feats['hippus_irregularity']:.3f} px/frame\n"
        f"(std of frame-to-frame change, {win_lo:.1f} to {win_hi:.1f} s)",
        ha="center", va="top", color="tab:orange", fontsize=13,
    )

    ax.set_xlim(0, DURATION_S)
    ax.set_ylim(23.0, 34.0)
    ax.set_xlabel("time (s)", fontsize=14)
    ax.set_ylabel("iris landmark distance (px)", fontsize=14)
    ax.tick_params(labelsize=12)
    ax.grid(alpha=0.3)
    ax.legend(loc="lower right", fontsize=12)
    fig.suptitle("SYNTHETIC SIGNAL, NOT REAL DATA", fontsize=26, fontweight="bold", color="firebrick")
    fig.text(
        0.5, 0.012, "Generated by scripts/demo_synthetic.py",
        ha="center", fontsize=11, color="0.35",
    )
    fig.tight_layout(rect=(0, 0.03, 1, 0.94))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    # Software=None keeps the matplotlib version string out of the PNG metadata.
    fig.savefig(OUT, metadata={"Software": None})
    print(f"wrote {OUT}")
    print({k: round(v, 3) for k, v in feats.items()})


if __name__ == "__main__":
    main()
